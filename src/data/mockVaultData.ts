function buildSeededDemoEnvelope(params: {
  ivHex: string;
  ivBase64: string;
  authTagHex: string;
  ciphertextBase64: string;
  ciphertextByteLength: number;
  sha256Hash: string;
  expectedSha256Hash?: string;
  recipientIds: string[];
  wrappedKeySeeds: string[];
  encryptedAt: string;
}): CryptoEnvelope {
  const recipients = getRecipientsByIds(params.recipientIds);
  return {
    algorithm: 'AES-256-GCM',
    keyWrapAlgorithm: 'RSA-OAEP-2048',
    ivHex: params.ivHex,
    ivBase64: params.ivBase64,
    authTagHex: params.authTagHex,
    ciphertextBase64: params.ciphertextBase64,
    ciphertextByteLength: params.ciphertextByteLength,
    sha256Hash: params.sha256Hash,
    expectedSha256Hash: params.expectedSha256Hash ?? params.sha256Hash,
    wrappedKeys: recipients.map((recipient, idx) => ({
      recipientId: recipient.id,
      recipientName: recipient.name,
      recipientRole: recipient.role,
      keyFingerprint: recipient.keyFingerprint,
      wrappedKeyBase64: params.wrappedKeySeeds[idx % params.wrappedKeySeeds.length],
    })),
    encryptedAt: params.encryptedAt,
    isWebCryptoReal: false,
  };
}

